package riskscore

// TestLearningCycleProvesFeedbackLoopWorks is the single artifact that
// directly answers "does the ML-based feedback loop actually do anything":
// it runs a full synthetic production cycle -- cold start, a batch of
// historical outcomes with a known pattern, a refit, and a fresh real-time
// nudge -- and asserts the model's score for two held-out reviews moves in
// the direction the synthetic incidents taught it, not just that nothing
// crashed. Run with -v; the logged before/after numbers are exactly what
// docs/risk-policy-explainability.md quotes as its worked example.
//
// See docs/risk-policy-engine.md §3 for the three update paths this test
// exercises (batch refit + the real-time online nudge; the third, on-demand
// refit, is the same code path as the batch refit under a different
// trigger, so it isn't a fourth variant here).

import (
	"context"
	"encoding/json"
	"math"
	"testing"
)

// weightDeltaRow is one weight's before/after, for the report's weight-delta
// table (see learningCycleDump, prefix "LCDATA:" -- regenerated by
// scripts/regen_risk_report.py, never hand-transcribed).
type weightDeltaRow struct {
	Name   string  `json:"name"`
	Before float64 `json:"before"`
	After  float64 `json:"after"`
	Delta  float64 `json:"delta"`
}

// logWeightDeltas prints every weight that changed by a meaningful amount
// between two model versions, by feature name -- the literal "why" behind a
// score change, not just the before/after score itself -- and returns the
// same data as a structured list for the JSON dump.
func logWeightDeltas(t *testing.T, label string, before, after Weights) []weightDeltaRow {
	t.Helper()
	t.Logf("weight changes (%s):", label)
	const noise = 1e-6
	var rows []weightDeltaRow
	if math.Abs(after[0]-before[0]) > noise {
		t.Logf("    bias: %.4f -> %.4f (delta %+.4f)", before[0], after[0], after[0]-before[0])
		rows = append(rows, weightDeltaRow{Name: "bias", Before: before[0], After: after[0], Delta: after[0] - before[0]})
	}
	for i, spec := range FeatureSpecs {
		if i+1 >= len(before) || i+1 >= len(after) {
			break
		}
		delta := after[i+1] - before[i+1]
		if math.Abs(delta) > noise {
			t.Logf("    %s: %.4f -> %.4f (delta %+.4f)", spec.Name, before[i+1], after[i+1], delta)
			rows = append(rows, weightDeltaRow{Name: spec.Name, Before: before[i+1], After: after[i+1], Delta: delta})
		}
	}
	if len(rows) == 0 {
		t.Logf("    (no weight moved by more than %.0e)", noise)
	}
	return rows
}

// learningCycleDump is the machine-readable record TestLearningCycleProvesFeedbackLoopWorks
// logs (prefix "LCDATA:") -- the report's learning-loop section is built
// directly from this, never hand-transcribed.
type learningCycleDump struct {
	NHistorical         int              `json:"n_historical"`
	ColdHigh            float64          `json:"cold_high"`
	ColdLow             float64          `json:"cold_low"`
	BatchHigh           float64          `json:"batch_high"`
	BatchLow            float64          `json:"batch_low"`
	HoldoutAUC          float64          `json:"holdout_auc"`
	OnlineHigh          float64          `json:"online_high"`
	ColdToBatchDeltas   []weightDeltaRow `json:"cold_to_batch_deltas"`
	BatchToOnlineDeltas []weightDeltaRow `json:"batch_to_online_deltas"`
}

func TestLearningCycleProvesFeedbackLoopWorks(t *testing.T) {
	db := testDB(t)
	orgID := seedOrg(t, db, "learning-cycle")
	store := NewStore(db)
	scorer := NewScorer(db)
	ctx := context.Background()

	// A held-out pair of reviews -- never inserted into training data, used
	// only to probe the model before and after each learning step. Chosen in
	// the model's non-saturated range (moderate blast radius, below the
	// "high" tier) deliberately, so the before/after movement this test
	// prints is a real, legible delta rather than a ceiling effect at ~1.0.
	highRisk := make([]float64, FeatureCount())
	highRisk[0], highRisk[1], highRisk[2] = 15, 15, 15 // br_sum / br_max / br_weighted_avg
	lowRisk := make([]float64, FeatureCount())
	lowRisk[0], lowRisk[1], lowRisk[2] = 2, 2, 2

	// --- Step 0: cold start. Every org begins at the shared common-sense
	// seed, with zero outcomes recorded. ---
	if err := store.EnsureSeedModel(ctx); err != nil {
		t.Fatalf("EnsureSeedModel: %v", err)
	}
	_, coldWeights, _, err := store.ActiveWeights(ctx, orgID)
	if err != nil {
		t.Fatalf("ActiveWeights (cold): %v", err)
	}
	coldHigh, err := scorer.ScoreFor(ctx, orgID, highRisk)
	if err != nil {
		t.Fatalf("ScoreFor (cold, high): %v", err)
	}
	coldLow, err := scorer.ScoreFor(ctx, orgID, lowRisk)
	if err != nil {
		t.Fatalf("ScoreFor (cold, low): %v", err)
	}
	t.Logf("step 0 (cold start, seed model, 0 outcomes):  high-blast-radius score=%.4f  low-blast-radius score=%.4f", coldHigh, coldLow)

	// --- Step 1: a batch of synthetic production history lands, with a
	// deliberate pattern: reviews whose blast radius was high got reverted;
	// reviews whose blast radius was low were later confirmed safe. This is
	// exactly what review_outcomes accumulating from real webhook/manual
	// reports over weeks would look like, compressed into one seeding pass. ---
	const nHistorical = 40
	for i := 0; i < nHistorical; i++ {
		features := make([]float64, FeatureCount())
		outcome := "confirmed_safe"
		if i%2 == 1 {
			// Moderate blast radius, varied a little so it's not two point
			// masses, and overlapping the held-out highRisk probe's range.
			v := 15.0 + float64(i%20)
			features[0], features[1], features[2] = v, v, v
			outcome = "revert"
		} else {
			v := float64(i % 10)
			features[0], features[1], features[2] = v, v, v
		}
		seedLabeledExampleFromSource(t, db, orgID, features, outcome, "ci")
	}

	refitRes, err := store.Refit(ctx, orgID)
	if err != nil {
		t.Fatalf("Refit: %v", err)
	}
	if !refitRes.Promoted {
		t.Fatalf("expected the batch refit to promote on %d cleanly separable historical outcomes, got reason: %s", nHistorical, refitRes.Reason)
	}
	if refitRes.HoldoutAUC < 0.75 {
		t.Fatalf("holdout AUC %.3f is too close to random for this cleanly separable synthetic history -- the mechanism doesn't appear to be learning", refitRes.HoldoutAUC)
	}
	Invalidate(orgID) // same invalidation SaveVersion already does; explicit here for clarity
	_, batchWeights, _, err := store.ActiveWeights(ctx, orgID)
	if err != nil {
		t.Fatalf("ActiveWeights (post-batch-refit): %v", err)
	}
	batchHigh, err := scorer.ScoreFor(ctx, orgID, highRisk)
	if err != nil {
		t.Fatalf("ScoreFor (post-batch-refit, high): %v", err)
	}
	batchLow, err := scorer.ScoreFor(ctx, orgID, lowRisk)
	if err != nil {
		t.Fatalf("ScoreFor (post-batch-refit, low): %v", err)
	}
	t.Logf("step 1 (after batch refit on %d historical outcomes, holdout AUC=%.3f): high-blast-radius score=%.4f (was %.4f, delta %+.4f)  low-blast-radius score=%.4f (was %.4f, delta %+.4f)",
		nHistorical, refitRes.HoldoutAUC, batchHigh, coldHigh, batchHigh-coldHigh, batchLow, coldLow, batchLow-coldLow)

	// WHY the score moved: log which specific weights changed and by how
	// much. This is the step the old report skipped -- it showed the score
	// jump but never showed the cause. The training data's pattern was
	// "elevated br_sum/br_max/br_weighted_avg correlates with reverts," so
	// those three weights, specifically, are what should move.
	coldToBatchDeltas := logWeightDeltas(t, "cold start -> after batch refit", coldWeights, batchWeights)

	if batchHigh <= coldHigh {
		t.Fatalf("after learning from reverted high-blast-radius history, the high-blast-radius score should have increased from the cold-start seed: %.4f -> %.4f", coldHigh, batchHigh)
	}
	if batchHigh <= batchLow {
		t.Fatalf("after the batch refit, the model must rank the high-blast-radius review above the low-blast-radius one: high=%.4f low=%.4f", batchHigh, batchLow)
	}

	// --- Step 2: a single new, real-time incident report (the "mark as
	// reverted" button / webhook path), on top of the just-refit model.
	// No batch job involved -- one gradient step, applied immediately. ---
	freshReviewID := seedReview(t, db, orgID)
	freshFeatures := make([]float64, FeatureCount())
	freshFeatures[0], freshFeatures[1], freshFeatures[2] = 15, 15, 15
	raw := mustMarshal(t, freshFeatures)
	if _, err := db.Exec(`
		INSERT INTO risk_feature_snapshots (review_id, org_id, model_version, features, score)
		VALUES ($1, $2, 1, $3, 0.5)`, freshReviewID, orgID, raw); err != nil {
		t.Fatalf("insert snapshot: %v", err)
	}
	if err := store.ApplyOutcome(ctx, orgID, freshReviewID, "revert"); err != nil {
		t.Fatalf("ApplyOutcome: %v", err)
	}
	Invalidate(orgID)
	_, onlineWeights, _, err := store.ActiveWeights(ctx, orgID)
	if err != nil {
		t.Fatalf("ActiveWeights (post-online-nudge): %v", err)
	}
	onlineHigh, err := scorer.ScoreFor(ctx, orgID, highRisk)
	if err != nil {
		t.Fatalf("ScoreFor (post-online-nudge, high): %v", err)
	}
	t.Logf("step 2 (after one additional real-time 'revert' report, no batch job): high-blast-radius score=%.4f (was %.4f after the refit, delta %+.4f)",
		onlineHigh, batchHigh, onlineHigh-batchHigh)
	batchToOnlineDeltas := logWeightDeltas(t, "after batch refit -> after one more real-time report", batchWeights, onlineWeights)

	if onlineHigh < batchHigh {
		t.Fatalf("a single additional revert report on a high-blast-radius review should not decrease the high-blast-radius score: %.4f -> %.4f", batchHigh, onlineHigh)
	}

	t.Logf("SUMMARY: cold-start high=%.4f -> after %d historical outcomes + refit high=%.4f -> after one more real-time report high=%.4f (total movement %+.4f, entirely from reported outcomes, zero manual weight edits)",
		coldHigh, nHistorical, batchHigh, onlineHigh, onlineHigh-coldHigh)

	dump := learningCycleDump{
		NHistorical: nHistorical, ColdHigh: coldHigh, ColdLow: coldLow,
		BatchHigh: batchHigh, BatchLow: batchLow, HoldoutAUC: refitRes.HoldoutAUC,
		OnlineHigh: onlineHigh, ColdToBatchDeltas: coldToBatchDeltas, BatchToOnlineDeltas: batchToOnlineDeltas,
	}
	dumpJSON, err := json.Marshal(dump)
	if err != nil {
		t.Fatalf("marshal learning cycle dump: %v", err)
	}
	t.Logf("LCDATA:%s", dumpJSON)
}
