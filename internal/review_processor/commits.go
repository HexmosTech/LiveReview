package reviewprocessor

import (
	"context"
	"database/sql"
	"fmt"
	"strings"
)

// CommitRef identifies a commit or commit range associated with a review.
type CommitRef struct {
	Ref     string
	Type    string // "commit" | "range"
	Message string // best-effort; empty when the source never provided one
}

// InsertReviewCommits records commit refs for a review (review_commits table), so a later
// coverage lookup can match on (org_id, ref); repositoryID may be nil when unknown. Lives here
// (not internal/api) so internal/jobqueue can call it too, without an import cycle.
func InsertReviewCommits(ctx context.Context, db *sql.DB, reviewID, orgID int64, repositoryID *int64, refs []CommitRef) error {
	if len(refs) == 0 {
		return nil
	}

	valueRows := make([]string, 0, len(refs))
	args := make([]interface{}, 0, len(refs)*6)
	argN := 1
	for _, r := range refs {
		ref := strings.TrimSpace(r.Ref)
		if ref == "" {
			continue
		}
		refType := strings.TrimSpace(r.Type)
		if refType != "range" {
			refType = "commit"
		}
		var message interface{}
		if msg := strings.TrimSpace(r.Message); msg != "" {
			message = msg
		}
		valueRows = append(valueRows, fmt.Sprintf("($%d, $%d, $%d, $%d, $%d, $%d)", argN, argN+1, argN+2, argN+3, argN+4, argN+5))
		args = append(args, reviewID, orgID, repositoryID, ref, refType, message)
		argN += 6
	}
	if len(valueRows) == 0 {
		return nil
	}

	// Safe: valueRows contains only $N parameter placeholders generated by
	// fmt.Sprintf above, never user-supplied values. Actual values are passed
	// through db.ExecContext's args parameter.
	// nosemgrep: go.lang.security.audit.database.string-formatted-query.string-formatted-query
	query := fmt.Sprintf(
		`INSERT INTO review_commits (review_id, org_id, repository_id, ref, ref_type, message) VALUES %s ON CONFLICT (review_id, ref) DO NOTHING`,
		strings.Join(valueRows, ", "),
	)
	_, err := db.ExecContext(ctx, query, args...)
	return err
}
