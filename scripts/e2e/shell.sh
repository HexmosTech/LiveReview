#!/usr/bin/env bash
# Interactive shell with the E2E run env and a sandboxed `lrc` function.
set -euo pipefail

DIR="$(cd "$(dirname "$0")" && pwd)"
# shellcheck source=common.sh
source "$DIR/common.sh"

if [[ ! -f "$E2E_DIR/run.env" ]]; then
  echo "No E2E run.env yet. Run 'make dev-up NICEURL=niceurl3' or 'make e2e-up'." >&2
  exit 2
fi

RC="$E2E_DIR/shellrc"
{
  echo "# Generated by scripts/e2e/shell.sh"
  echo "source '$E2E_DIR/run.env'"
  echo "lrc() { '$DIR/lrc.sh' \"\$@\"; }"
  echo "echo 'E2E shell: lrc is sandboxed; real ~/.lrc.toml is untouched.'"
} > "$RC"
chmod 600 "$RC"
exec "${SHELL:-bash}" --rcfile "$RC" -i
